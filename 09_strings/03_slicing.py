name = "Swarali0123456789"

print(name[2:-1])


print(name[0:10:2]) # This will print every second character from index 0 to 10
print(name[0:10:3])    # This will print every third character from the entire string

print(name[:1]) #In this case the empty space will be considered as 0
print(name[1:]) #In this case the empty space will be considered as the length of the string